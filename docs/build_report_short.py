"""Краткая версия предварительного отчёта (~3 страницы): docs/Предварительный_отчет_кратко.pdf."""

import os

import build_report as B  # noqa: E402  (стили, числа и форматирование — оттуда)

K, N, EV, IT, FIG, NM, REG = B.K, B.N, B.EV, B.IT, B.FIG, B.NM, B.REG
f1, f2, pct = B.f1, B.f2, B.pct


def _h1(self, t):  # в краткой версии допускаем заголовок ближе к низу страницы
    self.f += [B.CondPageBreak(130), K.P(t, K.S["h1"])]


K.Doc.h1 = _h1


def build():
    d = K.Doc()
    lr, rd = N["loo_regime"], N["regime_days"]
    own = [m for m in ["bootstrap", "ns", "ns_robust", "svensson", "ns_fix", "spline"] if m in lr]
    pr = {(a, b, r): (x, lo, hi) for a, b, r, x, lo, hi, _ in N["pairs"]}
    le = N["long_end"]
    boot, kbd = le.get("Бутстрэп (все выпуски)", {}), le.get("КБД Мосбиржи", {})
    mt, sp = EV["meetings"], EV["spreads"]
    r, v = IT["reaction"], IT["vol"]
    rgm = sp["by_regime"]
    st = pr.get(("ns", "bootstrap", "Стресс"), (0, 0, 0))
    sc = N["scenarios"]["Без длинных (> 10 лет)"]

    d.f.append(K.P("Восстановление кривой бескупонной доходности ОФЗ и сравнение методов в стрессовых режимах рынка",
                   K.S["title"]))

    d.h1("1. Задача и данные")
    d.p(f"Мы восстанавливаем кривую бескупонных ставок по ценам купонных ОФЗ-ПД и сравниваем методы, особенно в стрессовые "
        f"дни. Данные — Московская биржа и Банк России за январь 2024 — октябрь 2026 ({N['days']} торговых дней, "
        f"{N['n_min']}–{N['n_max']} выпусков в день). При подготовке данных мы исправили две ошибки: потерю купона, "
        "выплачиваемого в день расчётов по сделке, и некорректные средневзвешенные цены; после этого ошибка всех методов "
        "снизилась на 10–25%.")

    d.h1("2. Методы и критерии")
    d.p("Мы сравниваем бутстрэп, модели Нельсона–Сигеля и Свенссона (включая варианты с фиксированным τ, с привязкой к "
        "RUONIA и робастный) и сглаживающий сплайн форвардной кривой; эталон — КБД Мосбиржи. Основной критерий — ошибка вне "
        "выборки: каждую облигацию оцениваем по кривой, построенной без неё, на каждом дне. Стрессовые дни определяем по "
        "рынку — по волатильности 10-летней ставки и просадке индекса RGBI; получилось "
        f"{rd['Стресс']} стрессовых дней из {N['days']}. Значимость различий оцениваем блочным бутстрэпом.")
    d.image(FIG("fig_regimes.png"), "Рис. 1. Индекс RGBI, волатильность 10-летней ставки и ошибка методов вне выборки; "
            "фоном выделены стрессовые дни.", width=K.W * 0.78)

    d.h1("3. Результаты")
    d.table(["Метод"] + [f"{x} ({rd[x]} дн.)" for x in REG],
            [[NM[m]] + [f"{f1(lr[m][x][0])} [{f1(lr[m][x][1])}; {f1(lr[m][x][2])}]" for x in REG] for m in own],
            [2, 1.5, 1.5, 1.5])
    d.p("<i>Таблица 1. Ошибка вне выборки (RMSE, б.п. доходности) и 90%-ный доверительный интервал.</i>")
    d.p(f"Гладкие методы значимо точнее бутстрэпа во всех режимах, сильнее всего в стресс: Нельсон–Сигель выигрывает "
        f"{f1(-st[0])} б.п. Среди гладких методов лучший — обычный NS; сплайн, робастный NS и NS с фиксированным τ "
        "уступают ему от 0,5 до 4 б.п. Свенссон на тридцати бумагах избыточен. Бутстрэп переносит в кривую всю неоднородность цен, в том числе эффект купона, поэтому его "
        f"длинный конец неустойчив: средняя 20-летняя ставка {f1(boot.get('Ставка 20 лет, средн.'))}% против "
        f"{f1(kbd.get('Ставка 20 лет, средн.'))}% у КБД. Короткий конец кривой ОФЗ лежит примерно на "
        f"{f1(-N['ruonia_gap']['median'] / 100)} п.п. ниже RUONIA, поэтому привязка к денежному рынку ухудшает подгонку.")

    d.h1("4. Стресс и события")
    d.p("Регрессия ошибки на рыночные показатели показывает, что в стресс качество кривой падает прежде всего из-за "
        "сокращения ликвидности и числа торгуемых выпусков. Гладкие методы к этому устойчивее: если убрать все бумаги "
        f"длиннее 10 лет, ошибка бутстрэпа на них {f1(sc['Бутстрэп (все выпуски)']['Ошибка на убранных, б.п.'])} б.п., "
        f"у NS — {f1(sc['Нельсон–Сигель']['Ошибка на убранных, б.п.'])}.")
    d.p("Для ключевых дней — заседаний ЦБ, самых стрессовых и контрольных спокойных — мы построили кривые каждые 30 минут "
        "по внутридневным сделкам. Решение ЦБ в 13:30 отчётливо видно на кривой: у гладких методов 10-летняя ставка за "
        f"полчаса смещается в {f1(r['ns_jump_10']['ratio'])} раза сильнее обычного, у бутстрэпа — лишь в "
        f"{f1(r['bootstrap_jump_10']['ratio'])} раза из-за собственного шума метода. В стрессовые дни внутридневное движение "
        f"длинной ставки в {f1(v['Стресс']['ns']['rv10_bp'] / v['Спокойно']['ns']['rv10_bp'])} раза сильнее, чем в спокойные.")
    d.p(f"Фактические котировки bid/ask показали, что спред в стресс расширяется в "
        f"{f1(rgm['Стресс']['price_bp'] / rgm['Спокойно']['price_bp'])} раза, но остаётся на порядок меньше ошибок кривых: "
        "ошибки отражают различия между выпусками, а не шум котировок. Прогноз решений ЦБ по форвардам "
        f"({mt['n_eval']} заседаний) не превзошёл простые правила: коротких ОФЗ почти нет, а премия ОФЗ к денежному рынку "
        "нестабильна.")

    d.image(FIG("fig_intraday_meetings.png"), "Рис. 2. Ставки на 1 и 10 лет внутри дней заседаний ЦБ; пунктир — 13:30, "
            "момент публикации решения.", width=K.W * 0.72)

    d.h1("5. Выводы")
    d.p("Гладкие методы — Нельсон–Сигель, его вариант с фиксированным τ и сглаживающий сплайн — точнее бутстрэпа во всех "
        "режимах, сильнее всего в стресс; лучший результат у обычного NS. Робастный вариант NS преимущества не дал. "
        "Стресс ухудшает кривую в основном через падение ликвидности, поэтому отдельный "
        "стрессовый метод не требуется.")
    d.p("Результаты предварительные. Далее мы проверим чувствительность выводов к порогам стресса, повторим тест на "
        "шум цен с фактическим спредом, добавим ставки денежного рынка для короткого конца и попробуем учесть эффект купона "
        "и ликвидность выпусков при построении кривой.")

    out = os.path.join(B.HERE, "Предварительный_отчет_кратко.pdf")
    d.build(out, None, title="Кривая ОФЗ — предварительный отчёт (кратко)")
    print("PDF:", out)


if __name__ == "__main__":
    build()
