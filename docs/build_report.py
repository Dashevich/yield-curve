"""Предварительный отчёт для преподавателя: docs/Предварительный_отчет.pdf (числа — results/*.json)."""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pdfkit as K  # noqa: E402

RES = os.path.join(HERE, "..", "results")
N = json.load(open(os.path.join(RES, "numbers.json"), encoding="utf-8"))
EV = json.load(open(os.path.join(RES, "events.json"), encoding="utf-8"))
IT = json.load(open(os.path.join(RES, "intraday.json"), encoding="utf-8"))
FIG = lambda n: os.path.join(RES, n)
NM = {"bootstrap": "Бутстрэп", "bootstrap_1y": "Бутстрэп (1 выпуск/год)", "ns": "Нельсон–Сигель",
      "ns_robust": "NS робастный", "svensson": "Свенссон", "ns_fix": "NS, фикс. τ", "ns_anchor": "NS + якорь RUONIA",
      "spline": "Сглаживающий сплайн", "kbd": "КБД Мосбиржи"}
REG = ["Спокойно", "Обычно", "Стресс"]
IMG_W = K.W * 0.92

# чёрно-белое оформление (стили общего модуля меняем только для этого отчёта)
from reportlab.lib import colors  # noqa: E402
for _k in ("title", "h1", "h2", "caption", "body", "bullet", "cell"):
    K.S[_k].textColor = colors.black
K.S["cellb"].textColor = colors.black
K.NAVY = colors.HexColor("#E6E6E6")
K.GREY = colors.black
K.S["title"].fontSize, K.S["title"].leading, K.S["title"].spaceAfter = 18, 23, 12

# шрифт Times New Roman (если его нет в системе — метрически совместимый Liberation Serif)
from reportlab.pdfbase import pdfmetrics  # noqa: E402
K._font("TNR", ["times.ttf", "Times New Roman.ttf", "LiberationSerif-Regular.ttf"])
K._font("TNR-Bold", ["timesbd.ttf", "Times New Roman Bold.ttf", "LiberationSerif-Bold.ttf"])
K._font("TNR-Italic", ["timesi.ttf", "Times New Roman Italic.ttf", "LiberationSerif-Italic.ttf"])
K._font("TNR-BoldItalic", ["timesbi.ttf", "Times New Roman Bold Italic.ttf", "LiberationSerif-BoldItalic.ttf"])
pdfmetrics.registerFontFamily("TNR", normal="TNR", bold="TNR-Bold", italic="TNR-Italic", boldItalic="TNR-BoldItalic")
for _k, _f in {"title": "TNR-Bold", "h1": "TNR-Bold", "h2": "TNR-Bold", "body": "TNR", "bullet": "TNR",
               "caption": "TNR-Italic", "cell": "TNR", "cellb": "TNR-Bold"}.items():
    K.S[_k].fontName = _f
K.S["body"].fontSize, K.S["body"].leading = 12, 16
K.S["bullet"].fontSize, K.S["bullet"].leading = 12, 16
K.S["cell"].fontSize = K.S["cellb"].fontSize = 10
K.S["cell"].leading = K.S["cellb"].leading = 12.5
K.S["caption"].fontSize, K.S["caption"].leading = 10, 13
K.S["h1"].fontSize, K.S["h1"].leading = 14, 18

# заголовок раздела не оставляем внизу страницы без текста
from reportlab.platypus import CondPageBreak  # noqa: E402


def _h1(self, t):
    self.f += [CondPageBreak(220), K.P(t, K.S["h1"])]


K.Doc.h1 = _h1


def f1(x):
    return "—" if x is None else f"{x:.1f}".replace(".", ",")


def f2(x):
    return "—" if x is None else f"{x:.2f}".replace(".", ",")


def pct(x):
    return f"{x * 100:.0f}%"


def build():
    d = K.Doc()
    lr, rd = N["loo_regime"], N["regime_days"]
    own = [m for m in ["bootstrap", "ns", "ns_robust", "svensson", "ns_fix", "spline"] if m in lr]
    pr = {(a, b, r): (x, lo, hi) for a, b, r, x, lo, hi, _ in N["pairs"]}
    cs, bw = N["coupon_on_settle"], N["bad_waprice"]
    le = N["long_end"]
    boot, kbd = le.get("Бутстрэп (все выпуски)", {}), le.get("КБД Мосбиржи", {})
    mt, sp = EV["meetings"], EV["spreads"]
    r, v = IT["reaction"], IT["vol"]
    rgm = sp["by_regime"]

    d.f.append(K.P("Восстановление кривой бескупонной доходности ОФЗ и сравнение методов в стрессовых режимах рынка",
                   K.S["title"]))

    # ------------------------------------------------------------ 1
    d.h1("1. Задача и данные")
    d.p("Кривая бескупонных ставок нужна для оценки любых рублёвых денежных потоков, но на рынке она не наблюдается: "
        "её приходится восстанавливать по ценам примерно тридцати купонных выпусков ОФЗ. Мы сравниваем методы такого "
        "восстановления на данных 2024–2026 годов, когда рынок прошёл через ставку 21%, инверсию кривой, цикл смягчения и "
        "несколько распродаж, и отдельно смотрим на стрессовые дни.")
    d.p(f"Данные — Московская биржа (итоги торгов ОФЗ-ПД, графики купонов, КБД, индекс RGBI) и Банк России (ключевая "
        f"ставка, RUONIA, календарь заседаний): {N['days']} торговых дней, {N['n_min']}–{N['n_max']} выпусков в день. "
        "При подготовке данных мы нашли две ошибки. Купон, выплачиваемый в день расчётов по сделке (сделки вторника), "
        "выпадал из денежного потока — после исправления наша доходность совпала с биржевой в пределах ~1 б.п. вместо "
        f"~130 б.п. Кроме того, в {bw['rows']} строках средневзвешенная цена лежала вне дневного диапазона — их мы заменили "
        "ценой закрытия. Исправления снизили ошибку всех методов на 10–25% и изменили часть выводов по стрессу.")

    # ------------------------------------------------------------ 2
    d.h1("2. Методы и как мы их сравниваем")
    d.p("Мы реализовали методы трёх семейств. <b>Бутстрэп</b> строит кусочно-постоянные форварды между погашениями и "
        "проходит точно через каждую цену. <b>Параметрические модели</b> — Нельсон–Сигель и Свенссон — описывают всю "
        "кривую несколькими параметрами; к ним мы добавили варианты с фиксированным τ (подход Diebold–Li), с привязкой "
        "короткого конца к RUONIA и робастный вариант с функцией потерь Хьюбера. <b>Сглаживающий сплайн</b> форвардной "
        "кривой со штрафом на кривизну, растущим со сроком, — это подход, который используют Банк Англии и ФРС. "
        "Эталоном служит КБД Мосбиржи. Все модели калибруются по ошибкам в доходности, а не в цене, чтобы короткие и "
        "длинные бумаги вносили сопоставимый вклад. Гиперпараметры мы подбирали только на первой половине 2024 года, "
        "чтобы не подгонять методы под период, на котором их потом сравниваем.")
    d.p(f"Главный критерий — точность <b>вне выборки</b>: каждую облигацию мы оцениваем по кривой, построенной без неё "
        "(leave-one-out), и делаем это на каждом из дней. Стресс мы определяем не по календарю, а по рынку: день считается "
        "стрессовым, если волатильность 10-летней ставки выше 80-го перцентиля или индекс RGBI просел более чем на 7% от "
        f"квартального максимума. Получилось {rd['Стресс']} стрессовых, {rd['Обычно']} обычных и {rd['Спокойно']} спокойных "
        "дней; стресс оказался не одним эпизодом, а несколькими — весна–лето 2024, конец 2024, весна 2025 и лето 2026. "
        "Поскольку ошибки соседних дней коррелированы, значимость различий мы оцениваем блочным бутстрэпом. Кроме точности "
        "мы проверяли поведение длинного конца, устойчивость к пропаже выпусков и к шуму цен.")
    d.image(FIG("fig_regimes.png"), "Рис. 1. Индекс RGBI, волатильность 10-летней ставки и ошибка методов вне выборки; "
            "фоном выделены стрессовые дни.", width=IMG_W)

    # ------------------------------------------------------------ 3
    d.h1("3. Основные результаты")
    d.table(["Метод"] + [f"{x} ({rd[x]} дн.)" for x in REG],
            [[NM[m]] + [f"{f1(lr[m][x][0])} [{f1(lr[m][x][1])}; {f1(lr[m][x][2])}]" for x in REG] for m in own],
            [2, 1.5, 1.5, 1.5])
    d.p("<i>Таблица 1. Ошибка вне выборки (RMSE, б.п. доходности) и 90%-ный доверительный интервал.</i>")
    st = pr.get(("ns", "bootstrap", "Стресс"), (0, 0, 0))
    d.p(f"Гладкие методы оказались значимо точнее бутстрэпа во всех режимах, и сильнее всего разрыв проявляется в стресс: "
        f"там Нельсон–Сигель выигрывает {f1(-st[0])} б.п. (интервал от {f1(-st[2])} до {f1(-st[1])}). Среди гладких "
        "методов лучшим оказался обычный NS. Сплайн уступает ему около 1 б.п., NS с фиксированным τ — 2–4 б.п.: "
        "параметры этих методов мы подбирали только на первой половине 2024 года, и на последующем периоде они "
        "работают несколько хуже. Различия внутри этой группы малы по сравнению с разрывом с бутстрэпом. "
        f"Свенссон на тридцати бумагах избыточен: он хуже NS, а в {pct(N['at_bound']['svensson'])} дней его "
        "параметры упираются в границы. Привязка к RUONIA ухудшила кривую: короткий конец кривой ОФЗ в среднем на "
        f"{f1(-N['ruonia_gap']['median'] / 100)} п.п. ниже ставки денежного рынка, что мы связываем с премией за надёжность "
        "и ликвидность государственных бумаг.")
    rb = pr.get(("ns_robust", "ns", "Стресс"), (0, 0, 0))
    d.p("Отдельно мы проверили робастный вариант NS с функцией потерь Хьюбера, который должен быть менее чувствителен к "
        "аномальным ценам в стрессовые дни. До исправления ошибки с купоном он выигрывал у обычного NS, потому что "
        "ослаблял влияние как раз испорченных наблюдений. На очищенных данных преимущества у него нет: в стресс он "
        f"уступает обычному NS {f1(rb[0])} б.п.")
    d.p(f"Слабость бутстрэпа объясняется тем, что он переносит в кривую всё, что есть в ценах. Он конкурентоспособен на "
        f"сроках 3–7 лет, где выпусков много, но на длинном конце разваливается: средняя 20-летняя ставка у него "
        f"{f1(boot.get('Ставка 20 лет, средн.'))}% против {f1(kbd.get('Ставка 20 лет, средн.'))}% у КБД, а форварды выходят "
        f"за разумные пределы в {pct(N['boot_bad_share'])} дней. Отчасти это следствие эффекта купона, который мы "
        f"подтвердили регрессией: доходность бумаги систематически ниже на {f2(-N['coupon_reg']['Купон, за 1 п.п.'][0])} б.п. "
        "на каждый процентный пункт купона при прочих равных. Точная интерполяция превращает такую неоднородность самих "
        "бумаг в «пилу» на кривой.")
    d.image(FIG("fig_bootstrap_forwards.png"), "Рис. 2. Мгновенные форвардные ставки разных методов на одну дату: «пила» бутстрэпа — следствие эффекта купона.",
            width=IMG_W)

    # ------------------------------------------------------------ 4
    rg = N["regression"]
    sc = N["scenarios"]["Без длинных (> 10 лет)"]
    d.h1("4. Что происходит в стресс")
    d.p(f"Чтобы понять, откуда берётся рост ошибки в стрессовые дни, мы регрессировали дневную ошибку на рыночные "
        f"показатели. Для бутстрэпа главный фактор — волатильность ставок, а для всех методов значимы оборот и число "
        "торгуемых выпусков. Иначе говоря, стресс портит кривую прежде всего через сокращение информации: меньше сделок "
        "и меньше бумаг. Гладкие методы к этому заметно устойчивее, что подтвердили и сценарные тесты: если убрать все "
        f"бумаги длиннее 10 лет, ошибка бутстрэпа на них достигает {f1(sc['Бутстрэп (все выпуски)']['Ошибка на убранных, б.п.'])} "
        f"б.п., а у NS — {f1(sc['Нельсон–Сигель']['Ошибка на убранных, б.п.'])}. Поэтому специальный «стрессовый» метод, "
        "по нашим результатам, не требуется: достаточно гладкого метода.")
    d.p("Дневные данные, однако, смешивают в одно изменение все новости дня. Поэтому для ключевых дней мы перешли к "
        "внутридневным данным: по 10-минутным сделкам строили кривые каждые 30 минут в 23 днях заседаний ЦБ, 30 самых "
        "стрессовых и 30 спокойных днях. Решение ЦБ публикуется в 13:30, и сравнение кривых до и после этого момента "
        "изолирует реакцию рынка на само решение.")
    d.image(FIG("fig_intraday_meetings.png"), "Рис. 3. Ставки на 1 и 10 лет внутри дней заседаний ЦБ; пунктир — 13:30.",
            width=K.W * 0.7)
    d.p(f"Решения ЦБ видны на кривой очень отчётливо: за полчаса после 13:30 10-летняя ставка у гладких методов "
        f"смещается в {f1(r['ns_jump_10']['ratio'])}–{f1(r['spline_jump_10']['ratio'])} раза сильнее обычного получасового "
        f"движения, а у бутстрэпа — лишь в {f1(r['bootstrap_jump_10']['ratio'])} раза, потому что событие тонет в его "
        "собственном шуме. Почти вся дневная реакция приходится на первый час после решения. В стрессовые дни "
        f"внутридневное движение 10-летней ставки в {f1(v['Стресс']['ns']['rv10_bp'] / v['Спокойно']['ns']['rv10_bp'])} "
        "раза сильнее, чем в спокойные, и при этом имеет направленный характер — изменения продолжаются в ту же сторону, "
        "а не колеблются. У бутстрэпа даже в спокойные дни около "
        f"{pct(1 - (v['Спокойно']['ns']['rv10_bp'] / v['Спокойно']['bootstrap']['rv10_bp']) ** 2)} внутридневной дисперсии "
        "длинной ставки — шум метода.")
    d.p(f"Наконец, в файлах КБД мы нашли фактические котировки bid/ask на закрытие. Медианный спред составляет "
        f"{f1(sp['real_median_price_bp'])} б.п. цены и в стресс расширяется в "
        f"{f1(rgm['Стресс']['price_bp'] / rgm['Спокойно']['price_bp'])} раза. Это позволило проверить оценку спреда по "
        f"дневным максимумам и минимумам, которой мы пользовались раньше, — она оказалась завышенной примерно в "
        f"{f1(sp['cs_median_price_bp'] / sp['real_median_price_bp'])} раза. Важнее другое: ошибки кривых вне выборки на "
        "порядок больше полуспреда, то есть они отражают реальные различия между выпусками (купон, ликвидность), а не шум "
        "котировок. Поэтому дальнейшее повышение точности требует учёта этих различий, а не усложнения формы кривой.")

    # ------------------------------------------------------------ 5
    d.h1("5. Прогнозная сила кривой")
    d.p(f"Отдельно мы проверили, можно ли по форвардным ставкам предсказать решения ЦБ. Прогноз на год вперёд оказался "
        "неинформативным с точки зрения статистики — за период набирается меньше двух независимых наблюдений, — поэтому "
        f"мы перешли к горизонту одного заседания ({mt['n_eval']} проверок). Лучший вариант снижает ошибку прогноза ставки "
        f"с {f2(mt['nochange']['rmse'])} до {f2(mt['methods']['bootstrap']['regression']['rmse'])} п.п., но с учётом числа "
        "проверенных вариантов это различие незначимо, а простое правило «ЦБ сделает тот же шаг, что в прошлый раз» "
        f"угадывает направление в {pct(mt['momentum']['hit'])} случаев. Ограничение связано с самой кривой ОФЗ: в "
        f"{pct(mt['share_no_short'])} заседаний накануне не торговалось ни одной бумаги сроком до трёх месяцев, а премия "
        "ОФЗ к денежному рынку нестабильна. Для этой задачи естественнее инструменты денежного рынка, а внутридневная "
        "реакция кривой точнее отражает неожиданность решения, чем ожидания, извлечённые из неё накануне.")
    d.image(FIG("fig_meetings.png"), "Рис. 4. Ключевая ставка и ожидания, извлечённые из кривой накануне заседаний.",
            width=K.W * 0.78)

    # ------------------------------------------------------------ 6
    d.h1("6. Выводы и дальнейшая работа")
    d.p("Гладкие методы — Нельсон–Сигель, его вариант с фиксированным τ и "
        "сглаживающий сплайн — точнее бутстрэпа во всех режимах, сильнее всего в стресс; лучший результат у обычного NS, "
        "остальные гладкие методы уступают ему 1–4 б.п. Стресс ухудшает кривую в основном "
        "через падение ликвидности, а не через смену формы кривой. Исправление ошибок в данных изменило результаты "
        "сильнее, чем переход от одной модели к другой.")
    d.p("Результаты предварительные. Далее мы планируем: проверить, насколько выводы зависят от порогов определения стресса; повторить тест на шум "
        "цен с фактическим спредом bid/ask вместо оценки; добавить ставки денежного рынка (RUSFAR, свопы на RUONIA) для "
        "короткого конца и прогноза решений ЦБ; попробовать учесть эффект купона и ликвидность выпусков при построении "
        "кривой.")
    d.p("<b>Основные источники:</b> Nelson, Siegel (1987); Svensson (1994); Waggoner (1997); Anderson, Sleath (2001); "
        "Diebold, Li (2006); Diebold, Mariano (1995); Corwin, Schultz (2012); Kuttner (2001); Gürkaynak, Sack, Swanson "
        "(2005); методика КБД Московской биржи.")

    out = os.path.join(HERE, "Предварительный_отчет.pdf")
    d.build(out, None, title="Кривая ОФЗ — предварительный отчёт")
    print("PDF:", out)


if __name__ == "__main__":
    build()
