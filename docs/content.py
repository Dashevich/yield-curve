"""Содержание PDF: статичные разделы (content_static) + разделы с результатами (числа из numbers.json)."""

import content_static as S
import content_events as E


def write(d, N, FIG, f1, f0, pct, NM, OWN, REG):
    lr = N["loo_regime"]
    lb = N["loo_bucket"]
    le = N["long_end"]
    sc = N["scenarios"]
    rd = N["regime_days"]
    bw = N["bad_waprice"]
    cs = N["coupon_on_settle"]
    se = N["short_end"]
    gap = N["ruonia_gap"]
    pairs = {(a, b, r): (diff, lo, hi, v) for a, b, r, diff, lo, hi, v in N["pairs"]}

    def loo(m, r):
        v, lo, hi = lr[m][r]
        return f"{f1(v)} [{f1(lo)}; {f1(hi)}]"

    # ------------------------------------------------------------------ титул и суть
    d.title("Восстановление кривой процентных ставок по ОФЗ",
            "Объяснение проекта с нуля: понятия, данные, методы, результаты, стресс-анализ, слабые места и вопросы на защите. "
            "Версия 2 — с исправлениями и новыми проверками")
    d.h1("0. Суть в трёх предложениях")
    d.p("Государство занимает деньги, выпуская облигации (ОФЗ). По их ценам можно понять, под какой процент рынок даёт деньги "
        "на 1 год, на 5 лет, на 10 лет и так далее. Такой набор «срок → процент» называется <b>кривой процентных ставок</b>. "
        "Напрямую рынок её не показывает, поэтому её надо <b>восстановить</b> из цен облигаций. Мы сделали это восемью способами "
        "(трёх семейств), сравнили с официальной кривой Мосбиржи и проверили, какой способ лучше в разных рыночных условиях "
        "2024–2026 годов — отдельно в спокойные дни и в стресс.")

    d.h2("Что нового в этой версии (коротко)")
    d.bullets([
        f"<b>Найдены и исправлены две ошибки</b>, которые искажали прошлые результаты: (1) купон, который платится в сам день "
        f"расчётов по сделке, выкидывался из расчёта, хотя покупатель за него заплатил — это ломало {cs['rows']} наблюдений "
        f"(почти все — по вторникам) и раздувало ошибку на коротком конце; (2) в данных биржи у {bw['rows']} строк "
        "средневзвешенная цена лежит вне дневного диапазона торгов — теперь такие цены заменяются ценой закрытия.",
        "<b>Стресс определяется по рынку</b> (волатильность ставок и падение индекса RGBI), а не по календарю.",
        "<b>Проверка «исключи одного» — на всех 721 днях</b> (раньше на 72), с доверительными интервалами: "
        "теперь видно, какие различия между методами настоящие, а какие — случайность.",
        "<b>Четыре новых метода</b>: NS с фиксированным τ, NS с «якорем» на RUONIA, робастный NS (с функцией Хьюбера) и "
        "сглаживающий сплайн (как у Банка Англии и ФРС). Настройки методов подобраны только на первой половине 2024 года.",
        "<b>Новые стресс-тесты</b>: сценарии пропажи длинных/неликвидных бумаг, шум цен в пределах спреда, модельный риск в рублях, "
        "дни заседаний ЦБ, разложение движений кривой на главные компоненты.",
        "<b>Эффект купона проверен регрессией</b>, а прогноз форвардами — формальным тестом и на трёх вариантах «факта».",
        "<b>Точный взгляд на стресс (раздел 10)</b>: прогноз решения ЦБ «к следующему заседанию» (20 независимых проверок "
        "вместо двух), кривые <b>каждые 30 минут</b> в дни заседаний и самые стрессовые дни, и <b>настоящий спред бид/аск</b> "
        "из файлов Мосбиржи вместо оценки.",
    ])

    # ------------------------------------------------------------------ 1–7
    S.basics(d)
    S.why(d)
    S.data(d)
    S.bonds(d)
    d.box(f"<b>Вторая найденная ошибка — «купон в день расчётов».</b> Сделка на бирже исполняется на следующий день (T+1). "
          "Купоны ОФЗ обычно платятся по средам. Значит, у сделки во вторник расчёты — ровно в день купона. Покупатель в "
          "этом случае платит полный НКД и <b>получает</b> купон. А в коде стояло условие «берём выплаты <b>после</b> даты "
          "расчётов» — купон выпадал, и облигация выглядела дороже, чем есть, на целый купон (~3–4% цены). Для бумаги со "
          "сроком полгода это ошибка в доходности в несколько процентных пунктов. Мы сверили нашу доходность с той, что "
          "публикует сама биржа: с исправлением (выплаты «начиная с» даты расчётов) расхождение ~1 б.п., без него — ~130 б.п. "
          f"Затронуто {cs['rows']} наблюдений из {cs['of']} ({cs['rows'] / cs['of']:.1%}), {pct(cs['share_tuesday'])} из них — вторники. "
          "Мало, но все они на коротком конце, где ошибка и так самая большая.")
    S.methods(d, N, f1)
    S.comparison(d)

    # ------------------------------------------------------------------ 8. Результаты
    d.h1("8. Результаты и что они значат")
    d.image(FIG("fig_curves_key_dates.png"), "Кривые основных методов на три ключевые даты. Серые точки — доходности отдельных выпусков. "
            "Бутстрэп за пределами самого длинного выпуска уходит вниз; гладкие методы и КБД почти совпадают.")

    d.h2("8.1. Точность")
    d.p("<b>На выборке</b> (средняя за день ошибка по тем облигациям, по которым строили кривую, б.п.):")
    ins = N["in_sample"]
    per = list(next(iter(ins.values())).keys())
    rows = []
    for m in ["bootstrap", "bootstrap_1y", "ns", "svensson", "ns_fix", "ns_anchor", "spline", "kbd"]:
        vals = [ins[NM[m]][p] for p in per]
        rows.append([NM[m], f"{f0(min(vals))}–{f0(max(vals))}"])
    d.table(["Метод", "RMSE на выборке по периодам, б.п."], rows, [3, 2])
    d.p("Бутстрэп по построению проходит через все цены — его ошибка ≈ 0, и сравнивать его на выборке нечестно. КБД здесь "
        "хуже не потому, что она «плохая»: Мосбиржа строит её по своему набору облигаций и своим ценам и делает её "
        "стабильной от дня ко дню. Её задача — не подгонка под наши цены.")

    d.p("<b>Вне выборки</b> («исключи одного», все 721 день), по рыночным режимам. В скобках — 90%-ный доверительный интервал:")
    d.table(["Метод"] + [f"{r} ({rd[r]} дн.)" for r in REG],
            [[NM[m]] + [loo(m, r) for r in REG] for m in OWN], [2.2, 1.5, 1.5, 1.5])
    d.p("<b>Какие различия настоящие</b> (разница ошибок вне выборки; минус — первый метод точнее):")
    rows = []
    for a, b in [("ns", "bootstrap"), ("spline", "ns"), ("ns_fix", "ns"), ("svensson", "ns"), ("ns_anchor", "ns")]:
        row = [f"{NM[a]} − {NM[b]}"]
        for r in REG:
            x = pairs.get((a, b, r))
            row.append("—" if x is None else f"{f1(x[0])} [{f1(x[1])}; {f1(x[2])}] — <b>{x[3]}</b>")
        rows.append(row)
    d.table(["Сравнение"] + REG, rows, [2.2, 1.6, 1.6, 1.6])
    S_TEXT_ACCURACY(d, N, f1, f0, pct, NM, lr, pairs)

    d.p("<b>Ошибка вне выборки по срокам</b> (все дни), б.п.:")
    bks = list(lb[NM["ns"]].keys())
    d.table(["Срок"] + [NM[m] for m in ["bootstrap", "ns", "svensson", "ns_fix", "spline"]],
            [[k] + [f1(lb[NM[m]][k]) for m in ["bootstrap", "ns", "svensson", "ns_fix", "spline"]] for k in bks],
            [1.3, 1.4, 1.3, 1.1, 1.1, 1.3])
    sbk = se["buckets"]
    d.p("После исправления ошибки «купона в день расчётов» ошибка до 3 лет упала примерно с 53 до 33 б.п. (у NS) — "
        "большая часть «плохого короткого конца» в прошлой версии была именно этой ошибкой.")
    d.p(f"<b>Почему на коротком конце ошибка всё равно больше.</b> Посмотрим внутрь «до 3 лет» (NS): у бумаг до полугода "
        f"ошибка {f0(list(sbk.values())[0])} б.п., от полугода до года — {f0(list(sbk.values())[1])}, от 1 до 2 лет — "
        f"{f0(list(sbk.values())[2])}, от 2 до 3 — {f0(list(sbk.values())[3])}. Две причины:")
    d.bullets([
        "<b>Малая дюрация.</b> Ошибка в доходности ≈ ошибка в цене / дюрация. У бумаги со сроком 3 месяца дюрация 0,25 года: "
        "шум цены всего 0,1% даёт 40 б.п. доходности. Для 10-летней бумаги тот же шум — около 2 б.п. Короткие бумаги "
        "просто «звенят» сильнее.",
        f"<b>Экстраполяция.</b> Когда «исключаем» самую короткую бумагу, кривую левее неё нечем определить — она угадывается. "
        f"Ошибка на самой короткой бумаге дня {f0(se['shortest'])} б.п., а на остальных до 3 лет — {f0(se['rest_lt3'])}.",
    ])
    d.p(f"<b>Почему якорь на RUONIA не помог, а помешал.</b> Мы ожидали, что «ставка на сегодня» (RUONIA) подскажет левый край "
        f"кривой. Оказалось, что кривая ОФЗ на нулевом сроке стабильно лежит <b>на {f1(-gap['median'] / 100)} п.п. ниже RUONIA</b> "
        f"(половина дней — от {f1(-gap['q75'] / 100)} до {f1(-gap['q25'] / 100)} п.п.). Это не ошибка, а свойство рынка: ОФЗ — "
        "самый надёжный и ликвидный актив, банки держат их для сделок РЕПО с ЦБ и нормативов ликвидности и готовы ради этого "
        "получать меньше, чем по межбанковскому кредиту без залога (так называемая <b>премия за удобство</b>). Поэтому жёсткая "
        "привязка к RUONIA ±0,5 п.п. тянет кривую не туда: ограничение срабатывает в "
        f"{pct(N['short_active']['ns_anchor'])} дней, и ошибка растёт. Вывод для защиты: <b>RUONIA можно использовать как "
        "якорь только со сдвигом на этот спред</b>, а сам спред — интересная величина для отдельного исследования.")

    d.h2("8.2. Длинный конец — главная находка")
    bb = le[NM["bootstrap"]]
    d.p(f"<b>Бутстрэп ломается.</b> В {pct(N['boot_bad_share'])} дней его форвардные ставки выходят за пределы от 0% до 30%, "
        f"вплоть до отрицательных и до +80–90% — экономически это бессмыслица. Его 20-летняя ставка в среднем {f1(bb['Ставка 20 лет, средн.'])}% "
        f"(у КБД ≈ {f1(le[NM['kbd']]['Ставка 20 лет, средн.'])}%), а дневные колебания — {f0(bb['σ дневн. изм. 20 лет, б.п.'])} б.п. "
        f"против {f0(le[NM['kbd']]['σ дневн. изм. 20 лет, б.п.'])} у КБД.")
    rows = [[NM[m], f1(le[NM[m]]["Ставка 20 лет, средн."]), f0(le[NM[m]]["|20 лет − КБД|, б.п."]),
             f0(le[NM[m]]["σ дневн. изм. 20 лет, б.п."]), f"{f1(le[NM[m]]['Форвард 15→20 лет, мин.'])} … {f1(le[NM[m]]['Форвард 15→20 лет, макс.'])}"]
            for m in OWN + ["kbd"]]
    d.table(["Метод", "Ставка 20 лет, средн., %", "|20 лет − КБД|, б.п.", "Скачки 20 лет за день, б.п.", "Форвард 15→20 лет, мин … макс, %"],
            rows, [2.2, 1.1, 1.1, 1.1, 1.5])
    d.image(FIG("fig_bootstrap_forwards.png"), "Мгновенные форвардные ставки на последнюю дату: бутстрэп «пилит», Свенссон и сплайн гладкие.")
    S_TEXT_LONG(d, N, f1, f0, pct, NM, le)

    d.h2("Эффект купона: проверка регрессией")
    cm = N["coupon_means"]["ns"]
    cr = N["coupon_reg"]
    d.p(f"Простое сравнение: у NS выпуски с купоном меньше 8% в среднем «дороже» модели ({f1(cm[0])} б.п.), остальные — "
        f"«дешевле» ({f1(cm[1])} б.п.). Но низкий купон почти всегда означает <b>старый</b> выпуск (размещён в 2019–2021, когда "
        "ставки были 4–6%), а старые выпуски ещё и торгуются иначе. Чтобы отделить одно от другого, строим регрессию: ошибка "
        "модели по каждой облигации в каждый день — на купон, возраст выпуска, оборот и срок <b>одновременно</b>.")
    rows = [[k, f"{v[0]:+.2f}".replace(".", ","), f"{v[1]:+.1f}".replace(".", ",")] for k, v in cr.items() if k not in ("r2", "n")]
    d.table(["Фактор", "Влияние на ошибку, б.п.", "t-статистика"], rows, [2.5, 1.5, 1.2])
    S_TEXT_COUPON(d, N, f1, f0, cr)

    d.h2("8.3. Нехватка выпусков")
    dr = N["drop"]["0.5"]
    d.p("Убираем случайно половину облигаций — насколько сдвигается кривая (медиана, б.п.):")
    d.table(["Метод"] + REG, [[NM[m]] + [f1(dr[NM[m]][r]) for r in REG] for m in OWN], [2.2, 1, 1, 1])
    d.p("Гладкие модели гораздо устойчивее, когда данных мало, и это верно во всех режимах. Самый устойчивый — NS с "
        "фиксированным τ: у него меньше всего «свободы», и ему нечем подстраиваться под случайный набор бумаг.")

    d.h2("8.4. Форварды как прогноз")
    fk = N["forecast"]["3-мес. ставка КБД"]["kbd"]
    fkey = N["forecast"]["ключевая ставка ЦБ"]["kbd"]
    d.table(["«Факт»", "Смещение прогноза, п.п.", "Ошибка прогноза, п.п.", "Ошибка «не изменится», п.п.", "p-значение теста"],
            [["3-мес. ставка КБД", f1(fk[0]), f1(fk[1]), f1(fk[2]), f"{fk[4]:.2f}".replace(".", ",")],
             ["ключевая ставка ЦБ", f1(fkey[0]), f1(fkey[1]), f1(fkey[2]), f"{fkey[4]:.2f}".replace(".", ",")]],
            [1.8, 1.2, 1.2, 1.3, 1.1])
    d.p("Прогноз — форвард КБД; для остальных методов числа похожи (см. results/summary.md).")
    S_TEXT_FORECAST(d, N, f1, fk, fkey)
    d.image(FIG("fig_forward_forecast.png"), "Прогноз 3-месячной ставки через год по форвардам КБД против трёх «фактов» и наивного прогноза.")

    # ------------------------------------------------------------------ 9. Стресс
    stress_section(d, N, FIG, f1, f0, pct, NM, OWN, REG, loo)

    # ------------------------------------------------------------------ 10–13
    E.events_section(d, FIG, f1, f0, pct, NM)
    conclusions(d, N, f1, f0, pct, NM, loo)
    files_weak_questions(d, N, f1, f0, pct, NM)


# ---------------------------------------------------------------------- тексты, зависящие от чисел
def S_TEXT_ACCURACY(d, N, f1, f0, pct, NM, lr, pairs):
    ns_b = pairs[("ns", "bootstrap", "Стресс")]
    sp = [pairs.get(("spline", "ns", r)) for r in ("Спокойно", "Обычно", "Стресс")]
    d.p(f"<b>Как читать.</b> Гладкие методы (NS, сплайн, NS с фикс. τ) точнее бутстрэпа вне выборки во всех режимах, и это "
        f"<b>не случайность</b>: интервал разницы целиком ниже нуля. Сильнее всего разница в стресс — "
        f"{f1(-ns_b[0])} б.п. в пользу NS. Среди гладких лучший — обычный NS. Сплайн уступает ему около 1 б.п., NS с "
        "фиксированным τ — 2–4 б.п.: их настройки мы честно подбирали только на первой половине 2024 года, и дальше они "
        "работают чуть хуже. Робастный NS (с функцией Хьюбера) уступает обычному около 0,5 б.п. — на очищенных данных "
        "«гасить выбросы» уже незачем. Свенссон хуже NS во всех режимах — лишние параметры подстраиваются под шум.")
    d.p("<b>Где бутстрэп всё-таки хорош.</b> На середине кривой (3–7 лет), где бумаг много и они плотно стоят по сроку, "
        "бутстрэп вне выборки даже чуть точнее гладких методов (см. таблицу по срокам ниже). И в первом полугодии 2024 "
        "«бутстрэп по 1 выпуску в год» был точнее NS. Проблемы бутстрэпа — на краях кривой и в нервные дни.")
    d.p("<b>Неожиданное наблюдение.</b> Календарное «лето 2026» (раньше называли стрессом) оказалось для построения "
        "кривой <b>самым лёгким</b> периодом — ошибки вне выборки там минимальные (15–19 б.п.). Индекс падал, но цены "
        "бумаг двигались согласованно, и кривая хорошо описывалась любым методом. Это ещё один довод определять стресс "
        "по поведению рынка, а не по новостям.")
    d.box("<b>Что изменилось по сравнению с прошлой версией.</b> Раньше выходило, что «в стресс лета 2026 бутстрэп лучше "
          "(48 против 59 б.п.)». Это был артефакт: (1) по 4–5 дням, (2) с ошибкой данных 24.07.2026 и (3) с ошибкой «купона "
          "в день расчётов». После исправлений и расчёта по всем дням <b>бутстрэп не выигрывает ни в одном режиме</b>.")


def S_TEXT_LONG(d, N, f1, f0, pct, NM, le):
    sp = le[NM["spline"]]
    nf = le[NM["ns_fix"]]
    sv = le[NM["svensson"]]
    d.p("<b>Причина — эффект купона.</b> На длинных сроках есть облигации с низким купоном, например 26238 (7,1%) и 26230: "
        "они стоят дёшево (около 52–57% номинала). Рынок оценивает их дороже соседних облигаций с высоким купоном, поэтому "
        "их доходность ниже. Бутстрэп обязан пройти через обе цены, и когда «дорогая» и «дешёвая» облигации стоят рядом по "
        "сроку, ступенька форварда между ними становится огромной.")
    d.p(f"<b>Среди гладких методов</b> ближе всех к КБД на 20 годах — сплайн ({f0(sp['|20 лет − КБД|, б.п.'])} б.п.), "
        f"самая спокойная 20-летняя ставка — у NS с фиксированным τ (скачки {f0(nf['σ дневн. изм. 20 лет, б.п.'])} б.п. в день "
        f"против {f0(le[NM['kbd']]['σ дневн. изм. 20 лет, б.п.'])} у КБД). Свенссон — самый беспокойный из гладких "
        f"({f0(sv['σ дневн. изм. 20 лет, б.п.'])} б.п.).")
    ab = N["at_bound"]
