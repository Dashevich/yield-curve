"""Раздел 10: заседания ЦБ, внутридневные кривые и настоящий спред (числа — results/events.json, results/intraday.json)."""

import json
import os

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")


def load():
    ev = json.load(open(os.path.join(RES, "events.json"), encoding="utf-8"))
    intra = json.load(open(os.path.join(RES, "intraday.json"), encoding="utf-8"))
    return ev, intra


def events_section(d, FIG, f1, f0, pct, NM):
    ev, it = load()
    mt, sp = ev["meetings"], ev["spreads"]
    M = mt["methods"]
    nm = {**NM, "kbd": "КБД Мосбиржи"}

    def p2(x):
        return f"{x:.2f}".replace(".", ",")

    d.h1("10. Точный взгляд: заседания ЦБ, движения внутри дня и настоящий спред")
    d.p("В разделах 8–9 каждый день — одна точка: цена закрытия, одна кривая. Это грубо: за день на рынок приходят десятки "
        "новостей, и дневное изменение их все смешивает. Для стресс-анализа важнее <b>не длинный период, а точность в "
        "ключевые моменты</b>. Поэтому здесь три уточнения: (1) прогноз не «на год вперёд», а «на ближайшее заседание ЦБ» — "
        "так независимых наблюдений больше; (2) кривые <b>каждые 30 минут</b> внутри дня — в дни заседаний, в самые "
        "стрессовые и (для сравнения) в спокойные дни; (3) <b>настоящий спред</b> бид/аск вместо оценки.")

    # ---------------------------------------------------------------- 10.1
    d.h2("10.1. Может ли кривая предсказать следующее решение ЦБ")
    d.p("<b>Идея.</b> Накануне заседания смотрим на кривую и спрашиваем: какую ставку рынок «закладывает» на период "
        "действия нового решения — от понедельника после заседания до понедельника после следующего? Это <b>форвардная "
        "ставка</b> на этот отрезок. Если рынок ждёт снижения, она ниже текущей ключевой, если повышения — выше.")
    d.p(f"<b>Почему так лучше, чем «на год вперёд».</b> Каждое заседание — отдельное событие. За период их {mt['n_meetings']}, "
        f"проверяем на {mt['n_eval']} (первые три нужны для поправки, см. ниже), ставку меняли на {mt['n_moves']} из них. "
        "Это уже не «меньше двух независимых наблюдений», а двадцать.")
    d.p(f"<b>Проблема 1 — у кривой ОФЗ почти нет короткого конца.</b> В {pct(mt['share_no_short'])} заседаний накануне не "
        "торговалось ни одной ОФЗ со сроком меньше 3 месяцев. Тогда ставка «на 6 недель» — это продолжение линии от бумаг "
        "сроком от 3 месяцев, то есть скорее «средняя ставка на год», чем ожидание ближайшего решения. Для этого расчёта мы "
        "добавили короткие бумаги (от 2–3 недель), которые в основном расчёте отбрасывались как шумные.")
    d.p(f"<b>Проблема 2 — кривая ОФЗ лежит ниже денежного рынка.</b> Сырой форвард NS в среднем на {p2(-M['ns']['raw_bias'])} п.п. "
        f"ниже фактического решения (у КБД — на {p2(-M['kbd']['raw_bias'])} п.п.). Это та же «премия за удобство» ОФЗ, что в "
        "разделе 8. Поправку делаем двумя способами: (а) <b>«в реальном времени»</b> — сдвигаем форвард на среднюю ошибку по "
        "<b>прошлым</b> заседаниям (так можно было сделать в тот же день); (б) <b>регрессия</b> «изменение ставки ~ форвард − "
        "текущая ставка», оценённая без самого прогнозируемого заседания.")
    d.p("<b>С чем сравниваем.</b> «Ставку не изменят» и «ЦБ сделает тот же шаг, что в прошлый раз» (ЦБ действует циклами: "
        "начав снижать, обычно продолжает).")
    rows = [["«Не изменят»", p2(mt["nochange"]["rmse"]), pct(mt["nochange"]["hit"]), "—", "—"],
            ["«Тот же шаг»", p2(mt["momentum"]["rmse"]), pct(mt["momentum"]["hit"]),
             p2(mt["momentum"]["p_vs_nochange"]), "—"]]
    for m in ["bootstrap", "ns", "spline", "kbd"]:
        for tag, lab in (("realtime", "в реальном времени"), ("regression", "регрессия")):
            x = M[m][tag]
            rows.append([f"{nm[m]}, {lab}", p2(x["rmse"]), pct(x["hit"]), p2(x["p_vs_nochange"]), p2(x["p_vs_momentum"])])
    d.table(["Прогноз", "Ошибка, п.п.", "Угадано направление", "p против «не изменят»", "p против «тот же шаг»"],
            rows, [2.6, 1, 1.1, 1.2, 1.2])
    b = M["bootstrap"]["regression"]
    d.p("Ошибка — среднеквадратичная, в процентных пунктах ключевой ставки. «Направление» — снижение / пауза / повышение "
        "(изменение меньше 0,25 п.п. считаем паузой). p — тест Диболда–Мариано: меньше 0,05 — разница доказана.")
    d.bullets([
        f"<b>Лучший результат</b> — бутстрэп с короткими бумагами и регрессией: ошибка {p2(b['rmse'])} п.п. против "
        f"{p2(mt['nochange']['rmse'])} у «не изменят». Но p = {p2(b['p_vs_nochange'])}, а мы перепробовали "
        f"{mt['n_variants']} вариантов (6 кривых × 2 поправки) — при стольких попытках такая разница легко получается случайно. "
        "<b>Честный вывод: ни один вариант не предсказывает решение ЦБ доказуемо лучше простых правил.</b>",
        f"<b>Простое правило «тот же шаг, что в прошлый раз» угадывает направление в {pct(mt['momentum']['hit'])} случаев</b> — "
        "лучше любой кривой. Это свойство самого ЦБ (решения идут циклами), а не рынка.",
        "Бутстрэп здесь впервые выглядит не хуже гладких методов. Причина понятна: на самом коротком отрезке он просто "
        "проходит через цену ближайшей бумаги, а гладкие методы «усредняют» её с соседями. Для задачи «что будет через 6 "
        "недель» это плюс, для длинного конца — минус.",
        "<b>Почему так вышло.</b> Кривая ОФЗ — неудачный инструмент для прогноза ставки на 6 недель: коротких ОФЗ почти нет, "
        "а премия ОФЗ к денежному рынку плавает. Для такой задачи на практике используют денежный рынок — ставки RUSFAR "
        "на срок, процентные свопы на RUONIA (ROISfix). Это уже за рамками кривой ОФЗ; можно добавить как сравнение.",
    ])
    d.image(FIG("fig_meetings.png"), "Ключевая ставка (ступеньки) и что ожидалось накануне каждого заседания. Серые кружки — "
            "сырой форвард NS: всегда ниже, это премия ОФЗ. Красные — с поправкой по прошлым заседаниям; крестики — "
            "«тот же шаг, что в прошлый раз».")

    # ---------------------------------------------------------------- 10.2
    r = it["reaction"]
    d.h2("10.2. Что происходит внутри дня заседания")
    d.p(f"Банк России публикует решение в 13:30 по Москве. По 10-минутным сделкам мы строим кривую каждые 30 минут "
        f"(в среднем {f0(it['snapshots_per_day'])} кривых в день; цена бумаги — последняя сделка, не старше часа). "
        "Тогда реакцию на решение можно измерить почти «в чистом виде»: снимок в 13:30 — последний до решения.")
    d.image(FIG("fig_intraday_meetings.png"), "Все дни заседаний: ставки NS на 1 год (красная) и 10 лет (синяя) внутри "
            "дня, в б.п. от первого снимка. Пунктир — 13:30. Скачки ровно в момент решения видны почти везде.")
    d.bullets([
        f"<b>Решение видно сразу.</b> За полчаса после 13:30 10-летняя ставка NS сдвигается в среднем (медиана) на "
        f"{f1(r['ns_jump_10']['jump_bp'])} б.п. — это в {f0(r['ns_jump_10']['ratio'])} раз больше обычного получасового движения в "
        f"тот же день. У сплайна — в {f0(r['spline_jump_10']['ratio'])} раз. А у бутстрэпа — только в "
        f"{f0(r['bootstrap_jump_10']['ratio'])} раза: его собственный шум ({f1(r['bootstrap_jump_10']['usual_bp'])} б.п. за полчаса "
        f"против {f1(r['ns_jump_10']['usual_bp'])} у NS) «заглушает» событие. <b>Гладкие методы видят стресс-событие в 2 раза "
        "чётче.</b>",
        f"<b>Почти вся дневная реакция — в первый час.</b> Сумма движений с 13:30 до 14:30 равна сумме дневных движений "
        f"(отношение ≈ {f1(r['ns_share_1'])} для 1 года, {f1(r['ns_share_10'])} для 10 лет; больше 1 — потому что к вечеру часть "
        "реакции откатывается). Рынок ОФЗ переваривает решение ЦБ за час.",
        f"<b>Пример — 20.12.2024.</b> Все ждали повышения до 23%, ЦБ оставил 21%. За полчаса годовая ставка NS упала на "
        "1,6 п.п., 10-летняя — на 0,6 п.п. (за час — на 0,85). Наш прогноз по форвардам в тот день тоже ждал повышения — «сюрприз» совпал.",
        f"<b>Связь со «сюрпризом» из 10.1 слабая</b>: сюрприз объясняет около {pct(r['ns_win_1']['r2'])} реакции годовой ставки. "
        "Значит, ожидания рынка по кривой ОФЗ мы меряем плохо (см. 10.1), а вот <b>сама внутридневная реакция</b> — хорошая "
        "мера неожиданности решения. Так её и меряют в академических работах (Kuttner 2001, Gürkaynak–Sack–Swanson 2005).",
    ])

    # ---------------------------------------------------------------- 10.3
    v = it["vol"]
    d.h2("10.3. Стресс внутри дня: какой метод «шумит»")
    d.p("Насколько ставка ходит за день, если смотреть каждые 30 минут (корень из суммы квадратов получасовых изменений), "
        "медиана по дням, б.п.:")
    kinds = [k for k in ("Спокойно", "Стресс", "Заседание ЦБ") if k in v]
    d.table(["Метод"] + [f"2 года: {k.lower()}" for k in kinds] + [f"10 лет: {k.lower()}" for k in kinds],
            [[nm[m]] + [f1(v[k][m]["rv2_bp"]) for k in kinds] + [f1(v[k][m]["rv10_bp"]) for k in kinds]
             for m in ("bootstrap", "ns", "spline")], [1.6, 1, 1, 1, 1, 1, 1])
    vb, vn = v["Спокойно"]["bootstrap"]["rv10_bp"], v["Спокойно"]["ns"]["rv10_bp"]
    d.image(FIG("fig_intraday_vol.png"), "Внутридневное движение ставок на 2 и 10 лет по типам дней.")
    d.bullets([
        f"<b>В стресс 10-летняя ставка внутри дня ходит в {f1(v['Стресс']['ns']['rv10_bp'] / v['Спокойно']['ns']['rv10_bp'])} раза "
        "сильнее, чем в спокойный день</b> (по NS), в день заседания — ещё сильнее. Это и есть стресс «изнутри».",
        f"<b>Бутстрэп в спокойный день «двигается» вдвое больше гладких</b> ({f1(vb)} против {f1(vn)} б.п. на 10 лет), хотя рынок "
        "спокоен. Лишнее — это шум самого метода: дисперсия складывается, так что примерно "
        f"{pct(1 - (vn / vb) ** 2)} внутридневных движений его 10-летней ставки — шум.",
        f"Это подтверждает и автокорреляция получасовых изменений: у чистого шума она около −0,5 («дёрнулось и вернулось»), у "
        f"настоящего движения — около 0. У бутстрэпа на 10 лет {p2(v['Спокойно']['bootstrap']['ac10'])}, у NS "
        f"{p2(v['Спокойно']['ns']['ac10'])}. <b>В стресс у гладких методов она даже положительная</b> "
        f"({p2(v['Стресс']['ns']['ac10'])} у NS): внутри стрессового дня движение продолжается в ту же сторону — рынок "
        "не дёргается, а уверенно «едет».",
    ])

    # ---------------------------------------------------------------- 10.4
    s = it["spread"]
    rgm = sp["by_regime"]
    bm = sp["by_maturity"]
    d.h2("10.4. Настоящий спред бид/аск — и поправка к тесту на шум цен")
    d.p("Оказалось, что настоящие котировки у нас всё-таки есть. В файлах КБД, которые Мосбиржа публикует на конец дня, для "
        "каждой ОФЗ указаны лучшая цена покупки и лучшая цена продажи (снимок около 18:40–18:50). Это "
        f"{sp['n_obs']:,} наблюдений за все {sp['n_days']} дней.".replace(",", " "))
    d.table(["", "Спокойно", "Обычно", "Стресс"], [
        ["Настоящий спред, б.п. цены", f1(rgm["Спокойно"]["price_bp"]), f1(rgm["Обычно"]["price_bp"]), f1(rgm["Стресс"]["price_bp"])],
        ["То же в доходности, б.п.", f1(rgm["Спокойно"]["yield_bp"]), f1(rgm["Обычно"]["yield_bp"]), f1(rgm["Стресс"]["yield_bp"])],
        ["Оценка по дневным max/min (Corwin–Schultz), б.п. цены", f1(rgm["Спокойно"]["cs_price_bp"]),
         f1(rgm["Обычно"]["cs_price_bp"]), f1(rgm["Стресс"]["cs_price_bp"])],
    ], [2.6, 1, 1, 1])
    d.bullets([
        f"<b>В стресс спред шире в {f1(rgm['Стресс']['price_bp'] / rgm['Спокойно']['price_bp'])} раза</b>, чем в спокойные дни. "
        f"По срокам (по дюрации) в доходности: до 2 лет {f1(bm['0-2']['yield_bp'])} б.п., 2–5 лет {f1(bm['2-5']['yield_bp'])}, "
        f"5–8 лет {f1(bm['5-8']['yield_bp'])}, длиннее {f1(bm['8-40']['yield_bp'])} — короткие бумаги «шумят» сильнее всего, "
        "это ещё одна причина слабого короткого конца.",
        f"<b>Наша прежняя оценка спреда была завышена примерно в {f0(sp['cs_median_price_bp'] / sp['real_median_price_bp'])} раза</b> "
        f"({f0(sp['cs_median_price_bp'])} против {f1(sp['real_median_price_bp'])} б.п. цены), а с настоящим спредом по "
        f"бумагам совпадает слабо (корреляция {p2(sp['corr_bond_day'])}). Значит, в тесте 9.4 мы трясли цены втрое сильнее, "
        "чем на самом деле: <b>реальные сдвиги кривых от шума цен примерно втрое меньше</b> указанных в 9.4. Вывод "
        "«бутстрэп шумит сильнее гладких» не меняется — меняется только масштаб.",
        f"По внутридневным сделкам спред можно оценить точнее — методом Ролла (по тому, как цена «скачет» туда-обратно между "
        f"покупками и продажами): медиана {f1(s['Все']['roll_bp'])} б.п. против настоящих {f1(s['Все']['real_bp'])}, корреляция "
        f"{p2(s['Все']['corr_roll'])} против {p2(s['Все']['corr_cs_daily'])} у дневной оценки. А вот Corwin–Schultz на "
        "10-минутных свечах не работает вовсе (даёт почти ноль) — этот метод рассчитан на дневные данные.",
        "<b>Главный вывод про спред.</b> Ошибки кривых вне выборки (~25 б.п.) в десятки раз больше половины спреда (~1–2 б.п. "
        "в доходности). Только "
        f"{pct(sp['loo_inside_half_spread']['ns']['Все дни'])} ошибок NS укладываются в полуспред. Значит, ошибки кривых — это не "
        "«шум котировок», а <b>настоящие различия между бумагами</b>: эффект купона, ликвидность отдельных выпусков, спрос "
        "конкретных держателей. Улучшать точность дальше нужно моделированием этих эффектов, а не борьбой с шумом цен.",
    ])
